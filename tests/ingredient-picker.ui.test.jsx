test('uncertain batch saves retain the review and prevent repeated blind submissions',async()=>{
  const save=vi.fn().mockRejectedValue(new Error('offline'));const close=vi.fn();const user=userEvent.setup();render(<IngredientPicker onSave={save} onClose={close}/>);
  await user.click(screen.getByRole('checkbox',{name:'Select Rice'}));
  await user.click(screen.getByRole('button',{name:/Review selected/}));
  await user.click(screen.getByRole('button',{name:'Add 1 ingredient to pantry'}));
  expect(await screen.findByRole('alert')).toHaveTextContent('could not be confirmed');
  expect(screen.getByLabelText('Name for Rice')).toHaveValue('Rice');
  expect(save).toHaveBeenCalledTimes(1);
  await user.click(screen.getByRole('button',{name:'Return and check pantry'}));expect(close).toHaveBeenCalledTimes(1);
});
test('pantry launches the picker, saves selected items together and displays confirmed results',async()=>{
  let records=[];mocks.list.mockImplementation(async()=>records);mocks.saveMany.mockImplementation(async(items)=>{records=items.map((item,index)=>({...item,id:String(index)}));return records;});
  const user=userEvent.setup();render(<Pantry client={{}} userId="picker-evaluator"/>);
  await user.click(screen.getByRole('button',{name:/Add ingredients/}));
  await user.click(await screen.findByRole('checkbox',{name:'Select Apples'}));
  await user.click(screen.getByRole('checkbox',{name:'Select Carrots'}));
  await user.click(screen.getByRole('button',{name:/Review selected/}));
  expect(mocks.saveMany).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button',{name:'Add 2 ingredients to pantry'}));
  await screen.findByText('2 ingredients added to your pantry.');
  expect(await screen.findByRole('heading',{name:'Apples'})).toBeInTheDocument();
  expect(screen.getByRole('heading',{name:'Carrots'})).toBeInTheDocument();
  expect(mocks.saveMany).toHaveBeenCalledTimes(1);
  expect(screen.getByRole('button',{name:/Add ingredients/})).toHaveFocus();
});
