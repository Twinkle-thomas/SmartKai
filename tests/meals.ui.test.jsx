import React from 'react';
import { afterEach, beforeEach, expect, test, vi } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import MealPlanner from '../src/components/MealPlanner.jsx';
const mocks = vi.hoisted(() => ({ list: vi.fn(), save: vi.fn(), remove: vi.fn(), pantry: vi.fn(), shopping: vi.fn() }));
vi.mock('../src/services/meals.js', () => ({ createMealService: () => mocks }));
vi.mock('../src/services/pantry.js', () => ({ createPantryService: () => ({ list: mocks.pantry }) }));
vi.mock('../src/services/shopping.js', () => ({ createShoppingService: () => ({ save: mocks.shopping }) }));
beforeEach(() => {
  vi.resetAllMocks(); vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2026-11-03T00:00:00Z'));
  mocks.list.mockResolvedValue([]); mocks.pantry.mockResolvedValue([{ id: 'soup', name: 'Lentil soup', quantity: 2, unit: 'portions', location: 'Fridge', is_leftover: true, use_first: true }]);
});
afterEach(() => vi.useRealTimers());
const meal = { id: 'meal-1', name: 'Soup dinner', meal_date: '2026-11-03', meal_slot: 'Dinner', portions: 2, ingredients: 'Lentil soup', notes: '', includes_leftovers: true };
test('plan from pantry leftovers, save/edit, add a missing ingredient, reload and confirm deletion', async () => {
  let records = [];
  mocks.list.mockImplementation(async () => records);
  mocks.save.mockImplementation(async (item, id) => { records = [{ ...item, id: id ?? 'meal-1' }]; });
  mocks.remove.mockImplementation(async () => { records = []; });
  const user = userEvent.setup(); const view = render(<MealPlanner client={{}} userId="A" />);
  await user.type(screen.getByLabelText('Meal name'), 'Soup dinner');
  await user.selectOptions(screen.getByLabelText('Pantry food for meals'), 'Leftovers');
  await user.click(await screen.findByRole('button', { name: 'Use Lentil soup in meal notes' }));
  expect(screen.getByLabelText('Ingredient notes')).toHaveValue('Lentil soup');
  expect(screen.getByLabelText('Plan to use leftovers')).toBeChecked();
  expect(mocks.save).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Save meal plan' }));
  await screen.findByText('Meal planned.');
  await user.click(await screen.findByRole('button', { name: 'Edit meal Soup dinner' }));
  expect(screen.getByLabelText('Meal name')).toHaveFocus();
  await user.clear(screen.getByLabelText('Planned portions')); await user.type(screen.getByLabelText('Planned portions'), '3');
  await user.click(screen.getByRole('button', { name: 'Update planned meal' }));
  await screen.findByText('Meal plan updated.');
  await user.click(await screen.findByRole('button', { name: 'Shop for Soup dinner' }));
  expect(screen.getByLabelText('Missing ingredient name')).toHaveFocus();
  await user.type(screen.getByLabelText('Missing ingredient name'), 'Bread');
  await user.type(screen.getByLabelText('Missing ingredient quantity'), '1');
  await user.type(screen.getByLabelText('Missing ingredient unit'), 'loaf');
  await user.click(screen.getByRole('button', { name: 'Add missing ingredient to shopping' }));
  await screen.findByText('Missing ingredient added to your shopping list.');
  expect(mocks.shopping).toHaveBeenCalledWith(expect.objectContaining({ name: 'Bread', quantity: '1', unit: 'loaf', purchased: false, notes: 'For planned meal: Soup dinner (2026-11-03)' }));
  view.unmount(); render(<MealPlanner client={{}} userId="A" />);
  await user.click(await screen.findByRole('button', { name: 'Delete meal Soup dinner' }));
  expect(mocks.remove).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Keep planned meal' }));
  expect(mocks.remove).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Delete meal Soup dinner' }));
  await user.click(screen.getByRole('button', { name: 'Confirm meal deletion' }));
  await screen.findByText('Meal plan deleted.');
  await waitFor(() => expect(screen.queryByRole('button', { name: 'Edit meal Soup dinner' })).not.toBeInTheDocument());
});
test('week navigation and moving an edited meal to a different week reload the correct range', async () => {
  const user = userEvent.setup(); mocks.list.mockResolvedValue([meal]);
  render(<MealPlanner client={{}} userId="A" />);
  await user.click(await screen.findByRole('button', { name: 'Edit meal Soup dinner' }));
  await user.clear(screen.getByLabelText('Meal date')); await user.type(screen.getByLabelText('Meal date'), '2026-11-12');
  await user.click(screen.getByRole('button', { name: 'Update planned meal' }));
  await waitFor(() => expect(screen.getByLabelText('Week containing')).toHaveValue('2026-11-12'));
  expect(mocks.list).toHaveBeenLastCalledWith('2026-11-12');
  await user.click(screen.getByRole('button', { name: 'Previous week' }));
  await waitFor(() => expect(mocks.list).toHaveBeenLastCalledWith('2026-11-02'));
});
test('separate pantry/meal failures allow refresh and a failed save does not report success', async () => {
  mocks.list.mockRejectedValueOnce(new Error('offline')).mockResolvedValue([]);
  mocks.pantry.mockRejectedValue(new Error('offline')); mocks.save.mockRejectedValue(new Error('offline'));
  const user = userEvent.setup(); render(<MealPlanner client={{}} userId="A" />);
  await waitFor(() => expect(screen.getAllByRole('alert')).toHaveLength(2));
  await user.click(screen.getByRole('button', { name: 'Refresh meal plan' }));
  await user.type(screen.getByLabelText('Meal name'), 'Vegetable rice');
  await user.click(screen.getByRole('button', { name: 'Save meal plan' }));
  await screen.findByText(/The change could not be confirmed/);
  expect(screen.getByLabelText('Meal name')).toHaveValue('Vegetable rice');
  expect(screen.queryByText('Meal planned.')).not.toBeInTheDocument();
});
test('signed-out meal planning does not read private data', () => {
  render(<MealPlanner client={{}} />);
  expect(screen.getByRole('link', { name: 'Sign in to plan meals' })).toHaveAttribute('href', '#/login');
  expect(mocks.list).not.toHaveBeenCalled(); expect(mocks.pantry).not.toHaveBeenCalled();
});
