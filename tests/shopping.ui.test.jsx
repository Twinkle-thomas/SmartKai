test('shopping add/edit, pantry match, purchase/unpurchase, confirmed deletion and reload work', async () => {
  let records = [];
  mocks.list.mockImplementation(async () => records);
  mocks.save.mockImplementation(async (item, id) => { records = [{ ...item, id: id ?? 'shopping-1' }]; });
  mocks.setPurchased.mockImplementation(async (id, purchased) => { records = records.map((item) => ({ ...item, purchased })); });
  mocks.remove.mockImplementation(async () => { records = []; });
  const user = userEvent.setup(); const view = render(<ShoppingList client={{}} userId="A" />);
  await screen.findByText('No shopping items in this view yet.');
  await user.type(screen.getByLabelText('Shopping item name'), 'Apples');
  expect(await screen.findByText('Already recorded in your pantry')).toBeInTheDocument();
  await user.clear(screen.getByLabelText('Shopping quantity')); await user.type(screen.getByLabelText('Shopping quantity'), '4');
  await user.click(screen.getByRole('button', { name: 'Add shopping item', exact: true }));
  await screen.findByText('Shopping item added.');
  await user.click(await screen.findByRole('button', { name: 'Edit shopping Apples' }));
  expect(screen.getByLabelText('Shopping item name')).toHaveFocus();
  await user.type(screen.getByLabelText('Shopping notes'), 'Only if needed');
  await user.click(screen.getByRole('button', { name: 'Update shopping item' }));
  await screen.findByText('Only if needed');
  await user.click(screen.getByRole('checkbox', { name: 'Purchased Apples' }));
  await screen.findByText('Item marked purchased.');
  await user.selectOptions(screen.getByLabelText('Show shopping items'), 'Purchased');
  expect(await screen.findByRole('checkbox', { name: 'Purchased Apples' })).toBeChecked();
  view.unmount(); render(<ShoppingList client={{}} userId="A" />);
  await screen.findByText('No shopping items in this view yet.');
  await user.selectOptions(screen.getByLabelText('Show shopping items'), 'Purchased');
  await user.click(await screen.findByRole('checkbox', { name: 'Purchased Apples' }));
  await screen.findByText('Item moved back to your shopping list.');
  await user.selectOptions(screen.getByLabelText('Show shopping items'), 'To buy');
  await user.click(await screen.findByRole('button', { name: 'Delete shopping Apples' }));
  expect(mocks.remove).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Keep shopping item' }));
  expect(mocks.remove).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Delete shopping Apples' }));
  await user.click(screen.getByRole('button', { name: 'Confirm shopping deletion' }));
  await screen.findByText('Shopping item deleted.');
  await screen.findByText('No shopping items in this view yet.');
});
test('pantry failure is distinct from empty inventory and list operations can retry', async () => {
  mocks.list.mockRejectedValueOnce(new Error('offline')).mockResolvedValue([{ id: '1', name: 'Oats', quantity: 1, unit: 'bag', purchased: false, notes: '' }]);
  mocks.pantry.mockRejectedValue(new Error('offline'));
  mocks.setPurchased.mockRejectedValue(new Error('offline'));
  const user = userEvent.setup(); render(<ShoppingList client={{}} userId="A" />);
  await waitFor(() => expect(screen.getAllByRole('alert')).toHaveLength(2));
  expect(screen.getByText(/does not mean an item is out of stock/)).toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: 'Refresh shopping list' }));
  await user.click(await screen.findByRole('checkbox', { name: 'Purchased Oats' }));
  await screen.findByText(/The change could not be confirmed/);
  expect(screen.getByRole('checkbox', { name: 'Purchased Oats' })).not.toBeChecked();
});
